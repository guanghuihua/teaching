b.h('2. 一元二次方程的标准形式')
b.p('ax² + bx + c = 0（a ≠ 0）。只含一个未知数，整理后未知数的最高次数是 2。a、b、c 分别是二次项系数、一次项系数和常数项。')
b.p('先整理，再认系数：2x² = 3x + 2 → 2x² − 3x − 2 = 0。<br/>因此 a = 2，b = −3，c = −2。符号是系数的一部分！<br/>x² − 5 = 0 中，a = 1，b = 0，c = −5；没有的一次项，系数为 0。')
b.h('3. 解题前需要记住的三件事')
b.p('移项要变号：x² + 3x = 4 → x² + 3x − 4 = 0。<br/>去括号要顾到每一项：−2(x − 3) = −2x + 6。<br/>乘积为零：若 AB = 0，则 A = 0 或 B = 0。')
b.h('4. 两个常用因式分解公式')
b.p('平方差：x² − d² = (x − d)(x + d)。<br/>完全平方：x² + 2dx + d² = (x + d)²；<br/>　　　　　 x² − 2dx + d² = (x − d)²。')
b.p('例如：x² − 9 = (x − 3)(x + 3)；x² − 6x + 9 = (x − 3)²。<br/>提公因式也常用：x² − 3x = x(x − 3)。')
