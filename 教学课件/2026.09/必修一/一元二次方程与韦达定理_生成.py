ROOT = Path(__file__).resolve().parent
pdfmetrics.registerFont(TTFont('CN', 'C:/Windows/Fonts/msyh.ttc'))
pdfmetrics.registerFont(TTFont('CNB', 'C:/Windows/Fonts/msyhbd.ttc'))
STYLE = ParagraphStyle('body', fontName='CN', fontSize=11, leading=19, textColor=HexColor('#202a35'))

class Book:
    def __init__(self, name, label):
        self.c = canvas.Canvas(str(ROOT / name), pagesize=(595.28,841.89))
        self.c.setTitle(label); self.label=label; self.n=0
    def page(self, title, subtitle):
        if self.n: self.c.showPage()
        self.n+=1
        self.c.setFont('CN',9); self.c.setFillColor(HexColor('#526376'))
        self.c.drawString(46,807,'初高中衔接 · 一元二次方程与韦达定理')
        self.c.drawRightString(549,31,f'{self.label} · {self.n}')
        self.c.setStrokeColor(HexColor('#cad3dc')); self.c.line(46,793,549,793)
        self.c.setFont('CNB',21); self.c.setFillColor(HexColor('#173a57')); self.c.drawString(46,758,title)
        self.y=733; self.p(subtitle, color='#526376'); self.gap(8)
    def p(self, text, size=11, color='#202a35'):
        text=text.replace('₁','<sub>1</sub>').replace('₂','<sub>2</sub>')
        st=ParagraphStyle('p',parent=STYLE,fontSize=size,textColor=HexColor(color))
        p=Paragraph(text,st); _,h=p.wrap(503,740)
        if self.y-h<55: raise ValueError((self.n,text,self.y,h))
        p.drawOn(self.c,46,self.y-h); self.y-=h+7
    def h(self,text):
        self.gap(5); self.p(text,14,'#173a57')
    def gap(self,n): self.y-=n
    def work(self,n=68): self.gap(n)
    def save(self): self.c.save()

