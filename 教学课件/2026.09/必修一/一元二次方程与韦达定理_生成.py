b.h('方法一：直接开平方法')
b.p('当 u² = k 时：k &gt; 0，有 u = ±√k；k = 0，有 u = 0；k &lt; 0，无实数解。“±”表示正、负两种情况。')
b.p('例 1　解方程 (x − 1)² = 9。<br/>解：x − 1 = 3 或 x − 1 = −3，<br/>　　所以 x = 4 或 x = −2。<br/>检查：代入后分别得到 3² = 9 和 (−3)² = 9。')
b.p('易错：√9 = 3，但 x² = 9 的解是 x = ±3。算术平方根只有一个，方程的根可能有两个。')
b.h('方法二：因式分解法')
b.p('先把方程右边化为 0，再把左边写成两个因式的乘积。')
b.p('例 2　解方程 x² − 5x + 6 = 0。<br/>解：找两个数，和是 −5、积是 6，它们是 −2、−3。<br/>　　(x − 2)(x − 3) = 0，<br/>　　x − 2 = 0 或 x − 3 = 0，所以 x = 2 或 x = 3。')
b.p('例 3　解方程 x² = 3x。<br/>解：x² − 3x = 0 → x(x − 3) = 0，<br/>　　所以 x = 0 或 x = 3。<br/>易错：不能直接两边除以 x，因为 x 可能为 0，这样会漏掉根 0。')
b.h('方法三：配方法')
b.p('先把二次项系数化为 1，再移常数项；两边同加“一次项系数的一半的平方”。')
b.p('例 4　解方程 x² + 4x − 1 = 0。<br/>解：x² + 4x = 1，<br/>　　x² + 4x + 4 = 1 + 4（两边同加 (4/2)² = 4），<br/>　　(x + 2)² = 5 → x + 2 = ±√5，<br/>　　所以 x = −2 + √5 或 x = −2 − √5。')
b.page('03 公式法与韦达定理','目标：能代入公式求根，也能不求根就写出两根的和与积。')
b.h('方法四：公式法（适用于所有一元二次方程）')
b.p('先整理成 ax² + bx + c = 0（a ≠ 0），计算判别式 Δ = b² − 4ac。<br/>Δ &gt; 0：两个不相等的实数根；Δ = 0：两个相等的实数根；<br/>Δ &lt; 0：没有实数根。')
b.p('当 Δ ≥ 0 时，求根公式为：x = (−b ± √Δ)/(2a)。<br/>注意：整个分子 −b ± √Δ 都除以 2a。')
b.p('例 5　解方程 2x² − 3x − 2 = 0。<br/>a = 2，b = −3，c = −2；<br/>Δ = (−3)² − 4 × 2 × (−2) = 25。<br/>x = (3 ± 5)/4，所以 x = 2 或 x = −1/2。')
b.h('韦达定理：根与系数的关系')
b.p('若 ax² + bx + c = 0（a ≠ 0）有两个实数根 x₁、x₂（可相等），则<br/>x₁ + x₂ = −b/a，　x₁x₂ = c/a。<br/>记忆：根的和是“一次项系数的相反数 ÷ 二次项系数”，根的积是“常数项 ÷ 二次项系数”。')
b.p('为什么？a(x − x₁)(x − x₂) 展开为<br/>ax² − a(x₁ + x₂)x + ax₁x₂，比较系数就得到这两个关系。')
b.p('例 6　方程 2x² − 3x − 2 = 0 的两根满足：<br/>x₁ + x₂ = 3/2，x₁x₂ = −1。例 5 的两根确实满足这两个等式。')
b.h('不求根也能算：先变形，再代入')
